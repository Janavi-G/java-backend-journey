public class Nestedloop {
    public static void main(String[]args){
       //nested loop = a loop inside another loop
       //used often with matrices or DSA
       for(int i = 1;i<=3;i++){
            for(int j = 0;j<=9;j++){ 
                System.out.println(j+"");
            }
            System.out.println();
       } 
    }    
}